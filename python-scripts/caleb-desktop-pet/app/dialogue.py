class DialogueBook:
    def __init__(self):
        self.recent = deque(maxlen=20)

    def choose(self, category, affection):
        if category == 'warm' and affection < 30:
            category = 'idle'
        if category == 'close' and affection < 70:
            category = 'warm' if affection >= 30 else 'idle'
        pool = GROUPS.get(category, GROUPS['idle'])
        choices = [line for line in pool if line not in self.recent]
        if not choices:
            choices = [line for line in pool if not self.recent or line != self.recent[-1]]
        line = random.choice(choices)
        self.recent.append(line)
        return line
